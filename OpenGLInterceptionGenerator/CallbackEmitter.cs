using System.Linq;
using System.Text;

namespace OpenGLInterceptionGenerator;

/// <summary>Emits strongly typed native forwarding followed exclusively by post-call observation.</summary>
internal static class CallbackEmitter
{
    #region Internal API
    /// <summary>Creates one rooted callback factory without reflection or per-invocation allocation.</summary>
    internal static string Emit(NativeSignature signature, string observer, StateObservation? state = null)
    {
        string suffix = signature.Name.Substring(2);
        string parameters = string.Join(", ", signature.Parameters.Select((type, i) => type + " a" + i));
        string arguments = string.Join(", ", signature.Parameters.Select((_, i) => "a" + i));
        string abi = string.Join(", ", signature.Parameters.Concat(new[] { signature.Result }));
        bool returns = signature.Result != "void";
        string observationArguments = arguments + (returns ? (arguments.Length == 0 ? "" : ", ") + "result" : "");
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        source.AppendLine("namespace VanillaGraphicsExpanded.Rendering.RHI.Backends.OpenGL;");
        source.AppendLine("internal static unsafe partial class OpenGLBindingInterception\n{\n    #region Private");
        source.AppendLine("    /// <summary>Matches the audited native entrypoint ABI.</summary>");
        source.AppendLine("    [global::System.Runtime.InteropServices.UnmanagedFunctionPointer(global::System.Runtime.InteropServices.CallingConvention.StdCall)]");
        source.AppendLine($"    private delegate {signature.Result} {suffix}Callback({parameters});");
        source.AppendLine("    /// <summary>Forwards once before observation and retains the immutable original for callback lifetime.</summary>");
        source.AppendLine($"    private static OpenGLNativeSlot Create{suffix}(nint original)\n    {{");
        source.AppendLine($"        {suffix}Callback callback = ({arguments}) =>\n        {{");
        source.AppendLine($"            {(returns ? "var result = " : "")}((delegate* unmanaged[Stdcall]<{abi}>)original)({arguments});");
        source.AppendLine(state == null
            ? $"            try {{ if (ObservationEnabled) {observer}({observationArguments}); }}"
            : "            try { if (ObservationEnabled) Observe" + suffix + "(" + observationArguments + "); }");
        source.AppendLine("            catch (global::System.Exception) { /* Observation cannot escape or repeat native dispatch. */ }");
        if (returns) source.AppendLine("            return result;");
        source.AppendLine("        };\n        return new(original, callback);\n    }");
        if (state != null)
        {
            source.AppendLine("    /// <summary>Delivers the declared state effect with targeted originating-context recovery.</summary>");
            source.AppendLine($"    private static void Observe{suffix}({parameters})\n    {{");
            source.AppendLine(state.Emit(observer, observationArguments));
            source.AppendLine("    }");
        }
        source.AppendLine("    #endregion\n}");
        return source.ToString();
    }
    #endregion
}
