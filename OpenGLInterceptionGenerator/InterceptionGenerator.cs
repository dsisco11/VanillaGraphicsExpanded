using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using OpenGLInterceptionGenerator.Bindings;

namespace OpenGLInterceptionGenerator;

/// <summary>Validates attributed post-call observers and generates native callbacks and registration.</summary>
[Generator]
public sealed class InterceptionGenerator : IIncrementalGenerator
{
    private const string Owner = "VanillaGraphicsExpanded.Rendering.RHI.Backends.OpenGL.OpenGLBindingInterception";
    private static readonly DiagnosticDescriptor Invalid = new("GLI001", "Invalid native observer", "{0}", "Interception", DiagnosticSeverity.Error, true);

    #region Public API
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var methods = context.SyntaxProvider.ForAttributeWithMetadataName(
            "VanillaGraphicsExpanded.Rendering.RHI.Backends.OpenGL.InterceptOpenGLAttribute",
            static (node, _) => node is MethodDeclarationSyntax,
            static (target, _) => (IMethodSymbol)target.TargetSymbol).Collect();
        var drivers = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => DriverCallDiscovery.IsCall(node),
            static (syntax, _) => DriverCallDiscovery.Resolve(syntax)).Where(static call => call != null).Collect();
        context.RegisterSourceOutput(methods.Combine(drivers).Combine(context.CompilationProvider),
            static (output, input) => Generate(output, input.Left.Left, input.Left.Right, input.Right));
    }
    #endregion

    #region Private
    /// <summary>Rejects incomplete mappings before emitting a single authoritative registration catalog.</summary>
    private static void Generate(SourceProductionContext output, ImmutableArray<IMethodSymbol> methods, ImmutableArray<DriverCall?> drivers, Compilation compilation)
    {
        Dictionary<string, NativeSignature> signatures;
        Dictionary<string, (string EntryPoint, bool ScalarAddress)> driverEntries;
        try
        {
            var selectedNames = methods.SelectMany(method => method.GetAttributes().Where(attribute =>
                attribute.AttributeClass?.ToDisplayString() == "VanillaGraphicsExpanded.Rendering.RHI.Backends.OpenGL.InterceptOpenGLAttribute")
                .Select(attribute => attribute.ConstructorArguments.FirstOrDefault().Value as string ?? "")).ToArray();
            signatures = OpenTKSignatures.Read(compilation, selectedNames, drivers.Select(call => call!), out driverEntries);
        }
        catch (Exception error) when (error is FormatException or IOException or BadImageFormatException or InvalidOperationException or ArgumentException)
        {
            output.ReportDiagnostic(Diagnostic.Create(Invalid, Location.None, error.Message));
            return;
        }
        var generatedDrivers = new HashSet<string>(StringComparer.Ordinal);
        foreach (var driver in drivers)
        {
            if (!generatedDrivers.Add(DriverCallEmitter.Key(driver!))) continue;
            try
            {
                if (!driverEntries.TryGetValue(driver!.BindingKey, out var entry))
                    throw new FormatException("No native OpenTK call site for driver overload: " + driver.Method.ToDisplayString());
                output.AddSource("DriverCall" + generatedDrivers.Count + ".g.cs", SourceText.From(
                    DriverCallEmitter.Emit(driver, signatures[entry.EntryPoint], entry.ScalarAddress), Encoding.UTF8));
            }
            catch (FormatException error) { output.ReportDiagnostic(Diagnostic.Create(Invalid, driver!.Location, error.Message)); }
        }
        var selected = new HashSet<string>(StringComparer.Ordinal);
        var catalog = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace VanillaGraphicsExpanded.Rendering.RHI.Backends.OpenGL;\ninternal static partial class OpenGLBindingInterception\n{\n    #region Private\n    /// <summary>Resolves attributed native callbacks by authoritative entrypoint name.</summary>\n    private static OpenGLNativeSlot? CreateSlot(string name, nint original) => name switch\n    {\n");
        foreach (var method in methods.OrderBy(m => m.Name, StringComparer.Ordinal))
        {
            foreach (var attribute in method.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == "VanillaGraphicsExpanded.Rendering.RHI.Backends.OpenGL.InterceptOpenGLAttribute"))
            {
                string name = attribute.ConstructorArguments.FirstOrDefault().Value as string ?? "";
                string? error = null;
                if (!signatures.TryGetValue(name, out var signature)) error = "Unknown native entrypoint: " + name;
                else if (!selected.Add(name)) error = "Duplicate native observer: " + name;
                else if (!method.IsStatic || !method.ReturnsVoid || method.IsGenericMethod || (method.ContainingType.ToDisplayString() != Owner && method.DeclaredAccessibility is not (Accessibility.Internal or Accessibility.Public)))
                    error = "Observers must be accessible static, non-generic void methods";
                else
                {
                    var expected = signature.Parameters.Concat(signature.Result == "void" ? Array.Empty<string>() : new[] { signature.Result }).ToArray();
                    if (method.Parameters.Length != expected.Length || method.Parameters.Where((parameter, i) =>
                        parameter.RefKind != RefKind.None || parameter.Type.ToDisplayString() != expected[i]).Any())
                        error = "Observer signature must match native arguments followed by its return value: " + name;
                }
                if (error != null)
                {
                    output.ReportDiagnostic(Diagnostic.Create(Invalid, method.Locations.FirstOrDefault(), error));
                    continue;
                }
                output.AddSource(name + ".g.cs", SourceText.From(CallbackEmitter.Emit(signature!, (method.ContainingType.ToDisplayString() == Owner ? "" : "global::" + method.ContainingType.ToDisplayString() + ".") + "@" + method.Name), Encoding.UTF8));
                catalog.AppendLine($"        \"{name}\" => Create{name.Substring(2)}(original),");
            }
        }
        catalog.AppendLine("        _ => null\n    };\n    #endregion\n}");
        output.AddSource("NativeCatalog.g.cs", SourceText.From(catalog.ToString(), Encoding.UTF8));
    }
    #endregion
}
