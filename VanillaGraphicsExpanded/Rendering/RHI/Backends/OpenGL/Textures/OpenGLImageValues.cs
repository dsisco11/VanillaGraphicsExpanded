    /// <summary>Maps the image dimension to its native allocation target.</summary>
    internal static TextureTarget Target(RHITextureDimension dimension) => dimension switch
    {
        RHITextureDimension.One => TextureTarget.Texture1D,
        RHITextureDimension.Two => TextureTarget.Texture2D,
        RHITextureDimension.Three => TextureTarget.Texture3D,
        RHITextureDimension.OneArray => TextureTarget.Texture1DArray,
        RHITextureDimension.TwoArray => TextureTarget.Texture2DArray,
        RHITextureDimension.Cube => TextureTarget.TextureCubeMap,
        RHITextureDimension.CubeArray => TextureTarget.TextureCubeMapArray,
        RHITextureDimension.Rectangle => TextureTarget.TextureRectangle,
        RHITextureDimension.TwoMultisample => TextureTarget.Texture2DMultisample,
        RHITextureDimension.TwoMultisampleArray => TextureTarget.Texture2DMultisampleArray,
        _ => throw new ArgumentOutOfRangeException(nameof(dimension))
    };
    /// <summary>Translates established native image shape into semantic allocation policy.</summary>
    internal static RHITextureDimension Dimension(TextureTarget target) => target switch
    {
        TextureTarget.Texture1D => RHITextureDimension.One, TextureTarget.Texture2D => RHITextureDimension.Two,
        TextureTarget.Texture3D => RHITextureDimension.Three, TextureTarget.Texture1DArray => RHITextureDimension.OneArray,
        TextureTarget.Texture2DArray => RHITextureDimension.TwoArray, TextureTarget.TextureCubeMap => RHITextureDimension.Cube,
        TextureTarget.TextureCubeMapArray => RHITextureDimension.CubeArray, TextureTarget.TextureRectangle => RHITextureDimension.Rectangle,
        TextureTarget.Texture2DMultisample => RHITextureDimension.TwoMultisample, TextureTarget.Texture2DMultisampleArray => RHITextureDimension.TwoMultisampleArray,
        _ => throw new ArgumentOutOfRangeException(nameof(target))
