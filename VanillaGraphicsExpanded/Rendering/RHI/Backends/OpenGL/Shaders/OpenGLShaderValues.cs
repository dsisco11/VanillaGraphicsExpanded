    /// <summary>Decodes the resource category selected by native reflection.</summary>
    internal static ProgramResourceKind Resource(Native.ProgramInterface value) => value switch
    {
        Native.ProgramInterface.Uniform => ProgramResourceKind.Uniform,
        Native.ProgramInterface.UniformBlock => ProgramResourceKind.UniformBlock,
        Native.ProgramInterface.ShaderStorageBlock => ProgramResourceKind.ShaderStorageBlock,
        Native.ProgramInterface.AtomicCounterBuffer => ProgramResourceKind.AtomicCounterBuffer,
        Native.ProgramInterface.ProgramInput => ProgramResourceKind.ProgramInput,
        Native.ProgramInterface.ProgramOutput => ProgramResourceKind.ProgramOutput,
        _ => throw new ArgumentOutOfRangeException(nameof(value))
    };
    /// <summary>Decodes an observed stage after native stage validation.</summary>
    internal static ShaderStage Stage(Native.ShaderType value) => value switch
    {
        Native.ShaderType.VertexShader => ShaderStage.Vertex,
        Native.ShaderType.FragmentShader => ShaderStage.Fragment,
        Native.ShaderType.GeometryShader => ShaderStage.Geometry,
        Native.ShaderType.TessControlShader => ShaderStage.TessellationControl,
        Native.ShaderType.TessEvaluationShader => ShaderStage.TessellationEvaluation,
        Native.ShaderType.ComputeShader => ShaderStage.Compute,
        _ => throw new ArgumentOutOfRangeException(nameof(value))
    };
